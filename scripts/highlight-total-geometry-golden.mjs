import assert from 'node:assert/strict';
import { calculateHighlightTotalRatio as calc, getHighlightStageShapes, validateHighlightShape, getHighlightShapeFloorPoints } from '../src/utils/highlightTotalGeometry.ts';
const room = { x: 10, y: 20, width: 40, height: 20 };
const R=(x,y,width,height)=>({x,y,width,height});
const P=(points,drawMode='polygon')=>({kind:'polygon',drawMode,points});
const check=(args,percent,label)=>{const r=calc({room,...args});assert.equal(r.valid,true,`${label}: ${r.reason}`);assert.ok(Math.abs(r.percent-percent)<0.001,`${label}: ${r.percent} != ${percent}`);return r;};
check({},100,'empty total/main/sub = whole room');
check({total:[R(0,0,80,100)],main:[R(0,0,50,100)],sub:[R(0,0,40,100)]},50,'same total denominator, not main');
check({total:[R(0,0,100,100)],main:[R(0,0,70,100)],sub:[R(0,0,40,100)]},40,'sub is 40% of total even when main is 70%');
check({sub:[R(0,0,50,100),R(25,0,50,100)]},75,'union overlapping rectangles');
check({total:[R(25,0,50,100)],sub:[R(0,0,100,100)]},100,'total region independent base');
const tri=P([{x:0,y:0},{x:100,y:0},{x:0,y:100}]);
check({sub:[tri]},50,'triangle occupies half room');
const concave=P([{x:0,y:0},{x:100,y:0},{x:100,y:30},{x:30,y:30},{x:30,y:100},{x:0,y:100}]);
check({sub:[concave]},51,'concave L-shape area');
check({sub:[tri,tri]},50,'duplicate polygon union');
check({main:[R(0,0,50,100)],sub:[tri]},37.5,'triangle clipped by main');
check({total:[tri],sub:[R(0,0,50,100)]},75,'triangle total denominator');
const diagonal=P([{x:0,y:0},{x:100,y:100},{x:0,y:100}],'freehand');
assert.ok(validateHighlightShape(diagonal));
check({sub:[diagonal]},50,'freehand polygon');
assert.equal(validateHighlightShape(P([{x:0,y:0},{x:100,y:100},{x:100,y:0},{x:0,y:100}])),false,'self-intersection rejected');
assert.equal(calc({room,sub:[P([{x:0,y:0},{x:100,y:100},{x:100,y:0},{x:0,y:100}])]}).valid,false,'self-intersection cannot persist as auto qty');
assert.equal(calc({room:{...room,isPolyline:true},sub:[tri]}).valid,false,'open room invalid');
assert.equal(calc({room:{...room,width:0},sub:[tri]}).valid,false,'degenerate room invalid');
assert.equal(calc({room,total:[R(100,100,10,10)]}).valid,false,'empty total intersection invalid');
const old={highlightRegions:[R(0,0,70,100)],highlightVolumeMode:'area'};
assert.deepEqual(getHighlightStageShapes(old),old.highlightRegions,'legacy stage unchanged');
assert.deepEqual(getHighlightStageShapes({highlightVolumeMode:'manual'}),[],'legacy manual remains manual');
assert.deepEqual(getHighlightShapeFloorPoints(room,R(0,0,50,100)),[{x:10,y:20},{x:30,y:20},{x:30,y:40},{x:10,y:40}]);
const untouched=JSON.stringify(old);getHighlightStageShapes(old);assert.equal(JSON.stringify(old),untouched,'no data mutation');
const s=check({sub:[R(0,0,40,100)]},40,'total quantity mapping');
assert.equal(Math.round(200*s.ratio*10000)/10000,80,'200sqm total => 80sqm stage');
console.log('HIGHLIGHT TOTAL GEOMETRY GOLDEN PASS – legacy compatibility, polygon/concave/freehand, union, scoped denominator, no data writes');
