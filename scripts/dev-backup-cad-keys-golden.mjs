import assert from 'node:assert/strict';
import fs from 'node:fs';
import { applyCadDrawingGuide, CAD_GRID_STEP, getCadDrawingHotkey } from '../src/utils/roomHighlightCadShortcuts.ts';
const evt=(key,more={})=>({key,ctrlKey:false,altKey:false,metaKey:false,shiftKey:false,...more});
for(const key of ['F3','F7','F8','F9','F10']) assert.equal(getCadDrawingHotkey(evt(key)),key);
for(const key of ['F1','F2','F6','F11','Escape','ArrowLeft']) assert.equal(getCadDrawingHotkey(evt(key)),null);
for(const mod of ['ctrlKey','altKey','metaKey','shiftKey']) assert.equal(getCadDrawingHotkey(evt('F8',{[mod]:true})),null);
const size={width:800,height:400};
const none={gridSnap:false,ortho:false,polar:false};
assert.deepEqual(applyCadDrawingGuide({x:23,y:31},null,size,none),{x:23,y:31},'defaults should not alter drawing');
assert.equal(CAD_GRID_STEP,10);
assert.deepEqual(applyCadDrawingGuide({x:24,y:26},null,size,{...none,gridSnap:true}),{x:20,y:30},'F9 snaps to grid');
assert.deepEqual(applyCadDrawingGuide({x:35,y:31},{x:20,y:20},size,{...none,ortho:true}),{x:35,y:20},'F8 locks horizontal');
assert.deepEqual(applyCadDrawingGuide({x:21,y:60},{x:20,y:20},size,{...none,ortho:true}),{x:20,y:60},'F8 locks vertical');
const diagonal=applyCadDrawingGuide({x:30,y:40},{x:20,y:20},size,{...none,polar:true});
assert(Math.abs((diagonal.x-20)*size.width-(diagonal.y-20)*size.height)<0.001,'F10 aligns to 45° in screen coordinates');
assert.deepEqual(applyCadDrawingGuide({x:34,y:70},{x:20,y:20},size,{...none,polar:true}),{x:34,y:70},'F10 does not distort off-angle lines');
assert.deepEqual(applyCadDrawingGuide({x:99,y:110},null,size,none),{x:99,y:100},'final points remain in bounds');
const app=fs.readFileSync('src/components/FloorPlanDefectTab.tsx','utf8');
for(const token of ['getCadDrawingHotkey(e)','if (e.repeat) return','room_object_snap_enabled','room_cad_grid_visible','room_cad_ortho','room_cad_grid_snap','room_cad_polar','applyCadDrawingGuide','data-hnl-cad-grid="true"'])assert(app.includes(token),'Missing shortcut integration '+token);
assert(app.includes("updateSnapPref('room_cad_polar', false, setCadPolar)") && app.includes("updateSnapPref('room_cad_ortho', false, setCadOrtho)"),'Ortho/Polar must mutually exclude');
assert(app.includes("if (cadKey === 'F7' || canManageStructure)"),'Viewer cannot alter structural modes');
assert(app.includes('pointer-events-none z-[5]'),'Grid must not intercept pointer events');
assert(app.includes('target.closest('), 'Ignore shortcuts while a dialog owns focus');
assert(!app.includes('data-hnl-cad-toolbar='),'Never add new CAD toolbar UI');
assert(fs.existsSync('src/utils/roomHighlightObjectSnap.ts'),'Prior OSNAP candidate must be retained');
console.log('PASS HNL CAD keyboard-only F3/F7/F8/F9/F10 pure geometry and source gating');
