const stock = (type, quantity, onHand) => calculateRestoredWarehouseBalance(onHand, { type, quantity });
assert.equal(stock('in', 10, 3), 13, 'restoring IN must credit inventory once');
assert.equal(stock('out', 10, 15), 5, 'restoring OUT must debit inventory once');
assert.equal(stock('out', 10, 10), 0, 'restoring OUT may consume exact on-hand');
assert.equal(stock('in', 10, 0), 10, 'restoring IN can replenish zero stock');
assert.throws(() => stock('out', 10, 9.99), /INSUFFICIENT_STOCK_RESTORE/, 'concurrent issues must block unsafe OUT restore');
assert.throws(() => stock('out', 10, 0), /INSUFFICIENT_STOCK_RESTORE/, 'restore cannot create negative balance');
assert.throws(() => stock('in', 10, Number.NaN), /INVENTORY_RESTORE_INVALID_BALANCE/, 'NaN stock fails closed');
assert.throws(() => stock('in', 10, -5), /INVENTORY_RESTORE_INVALID_BALANCE/, 'negative stock fails closed');
assert.throws(() => stock('in', 0, 5), /INVENTORY_LEDGER_INVALID_QUANTITY/, 'invalid quantity fails closed');
