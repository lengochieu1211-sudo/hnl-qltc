import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import { validateDevTarget } from './dev-firebase-switch.mjs';
import { BACKUP_ID, BACKUP_GATEWAY } from './dev-backup-hosting.mjs';

let count = 0;
const test = (name, fn) => { fn(); count++; console.log(`PASS FIRST PARTY AUTH: ${name}`); };
const env = fs.readFileSync('.env.dev-backup.example', 'utf8');
const checked = validateDevTarget(env, 'backup');
const vars = checked.values;
const src = fs.readFileSync('src/lib/firebaseBase.ts','utf8');
const main = fs.readFileSync('src/main.tsx','utf8');
const persistence = fs.readFileSync('src/lib/authPersistence.ts','utf8');
const sha = s => crypto.createHash('sha256').update(s).digest('hex');
const host = 'hnl-qltc-dev-backup.web.app';
test('DEV BACKUP selected explicitly', () => assert.equal(checked.projectId, BACKUP_ID));
test('Firebase Auth helper uses SAME origin as app web.app', () => assert.equal(vars.get('VITE_FIREBASE_AUTH_DOMAIN'), host));
test('R2 Gateway matches existing live backup endpoint', () => assert.equal(vars.get('VITE_R2_GATEWAY_URL'), BACKUP_GATEWAY));
test('Firebase project remains backup', () => assert.equal(vars.get('VITE_FIREBASE_PROJECT_ID'), BACKUP_ID));
test('Firebase emulator disabled in hosting build', () => assert.equal(vars.get('VITE_USE_FIREBASE_EMULATORS'), 'false'));
test('no backup-only cross-domain auth handoff', () => assert.ok(!src.includes('getBackupMobileLoginHandoffUrl') && !main.includes('getBackupMobileLoginResumeCleanUrl')));
test('no previous URL one-shot login marker', () => assert.ok(!src.includes('_hnl_backup_google_login') && !main.includes('_hnl_backup_google_login')));
test('mobile uses Firebase native signInWithRedirect', () => assert.ok(src.includes('await signInWithRedirect(auth, provider)')));
test('desktop still uses Firebase native signInWithPopup', () => assert.ok(src.includes('await signInWithPopup(auth, provider)')));
test('Google provider retains account chooser', () => assert.ok(src.includes("provider.setCustomParameters({ prompt: 'select_account' })")));
test('Auth redirect completion before app UI', () => assert.ok(main.indexOf('await completeFirebaseAuthRedirect()') < main.indexOf("import('./App.tsx')")));
test('redirect result consumed via Firebase SDK', () => assert.ok(persistence.includes('await getRedirectResult(auth)')));
test('Auth persistence local/session/memory fallback intact', () => assert.ok(['browserLocalPersistence','browserSessionPersistence','inMemoryPersistence'].every(s=>persistence.includes(s))));
test('store/restore Google identity remains real Firebase Auth', () => assert.ok(src.includes("throw new Error('Không thể đăng nhập Google/Firebase")));
test('backup media cloud writer disabled', () => assert.equal(vars.get('VITE_WAREHOUSE_TRUSTED_WRITER'), 'false'));
test('source version 6.3.0 unchanged', () => assert.equal(JSON.parse(fs.readFileSync('package.json')).version,'6.3.0'));
test('same underlying sign-in as original HNL app with no relay', () => assert.equal(sha(src), 'b188d9a0af7d42760641804d6527a860deacd8df32f7be5cf4c27680650647cb')); // replaced with observed parent SHA below
console.log(`${count}/${count} first-party DEV BACKUP Google Auth source tests PASS (not device Runtime Golden)`);
